# --- one site client --------------------------------------------------------------------------
ensure_site() {
  local site=$1 client origin callback post_logout uuid created=false live_flags post_logout_live
  local core_scope core_scope_uuid core_ok sa_name line name rest kind scope_name scope_id
  local -A default_scopes=() optional_scopes=()
  local good=() bad_client=() own_groups_line=''
  client="frontend-$site"
  origin=$(site_origin "$site")
  callback="$origin/api/auth/callback/keycloak"
  post_logout="$origin/*"
  core_scope="$client-core-audience"

  # 1. the client and its flags and URIs
  uuid=$(uuid_by "$client")
  if [[ -z $uuid ]]; then
    change "create confidential client $client (standard flow with PKCE S256 and service account on, implicit and direct grants off, fullScopeAllowed=false; redirect $callback, web origin $origin, post-logout $post_logout; the secret is generated by Keycloak and never printed)"
    if [[ $MODE == apply ]]; then
      uuid=$(kcadm create clients -r "$TARGET_REALM" -i \
        -s "clientId=$client" \
        -s "name=$(site_name "$site")" \
        -s "description=${origin#https://}: NextAuth login and server-side CMS reads (Site client, ADR-0056). Made by config/site-clients.sh" \
        "${FLAG_SETTINGS[@]}" \
        -s "redirectUris=$(json_strings "$callback")" \
        -s "webOrigins=$(json_strings "$origin")" \
        -s "attributes.\"post.logout.redirect.uris\"=$post_logout" | tr -d '\r')
      [[ -n $uuid ]] || { printf 'client %s was not created\n' "$client" >&2; exit 1; }
      created=true
    fi
  else
    live_flags=$(csv "clients/$uuid" "$FLAG_FIELDS")
    if [[ $live_flags == "$FLAG_VALUES" ]]; then
      log "$client: flags unchanged ($FLAG_FIELDS=$live_flags)"
    else
      change "update $client flags ($FLAG_FIELDS: $live_flags -> $FLAG_VALUES)"
      if [[ $MODE == apply ]]; then
        kcadm_write update "clients/$uuid" -r "$TARGET_REALM" "${FLAG_SETTINGS[@]}"
      fi
    fi
    ensure_uris "$client" "$uuid" redirectUris "$callback" 'redirect URI'
    ensure_uris "$client" "$uuid" webOrigins "$origin" 'web origin'
    post_logout_live=$(csv "clients/$uuid" 'attributes(post.logout.redirect.uris)')
    if [[ $post_logout_live == "$post_logout" ]]; then
      log "$client: post-logout redirect exactly $post_logout"
    else
      change "set the post-logout redirects of $client to exactly $post_logout${post_logout_live:+ (was ${post_logout_live//##/ })}"
      if [[ $MODE == apply ]]; then
        kcadm_write update "clients/$uuid" -r "$TARGET_REALM" -s "attributes.\"post.logout.redirect.uris\"=$post_logout"
      fi
    fi
  fi
  [[ $created == false ]] || log "$client: created (id $uuid; the secret is never printed)"

  # 2. what reaches the access token: the client's mappers and its default and optional scopes.
  # A client still to be made (--check) would get the realm's default and optional scopes.
  if [[ -n $uuid ]]; then
    while IFS=, read -r scope_id scope_name; do
      if [[ -n $scope_id ]]; then default_scopes[$scope_name]=$scope_id; fi
    done < <(csv "clients/$uuid/default-client-scopes" id,name)
    while IFS=, read -r scope_id scope_name; do
      if [[ -n $scope_id ]]; then optional_scopes[$scope_name]=$scope_id; fi
    done < <(csv "clients/$uuid/optional-client-scopes" id,name)
  else
    while IFS=, read -r scope_id scope_name rest; do
      if [[ -n $scope_id && $rest == openid-connect ]]; then default_scopes[$scope_name]=$scope_id; fi
    done < <(csv default-default-client-scopes id,name,protocol)
    while IFS=, read -r scope_id scope_name rest; do
      if [[ -n $scope_id && $rest == openid-connect ]]; then optional_scopes[$scope_name]=$scope_id; fi
    done < <(csv default-optional-client-scopes id,name,protocol)
  fi

  # 3. aud skycms: the shared scope
  if [[ $skycms_scope_ok == true ]]; then
    attach_default "$client" "$uuid" "$SKYCMS_SCOPE" "$skycms_scope_uuid"
  fi

  # 4. aud core: the site's own scope
  if [[ -z $core_uuid ]]; then
    log "NOTE: realm $TARGET_REALM has no $CORE_CLIENT client; $core_scope skipped (rerun once core's client exists)"
  else
    core_ok=true
    ensure_audience_scope "$core_scope" "$CORE_CLIENT" "$CORE_MAPPER" || core_ok=false
    core_scope_uuid=$SCOPE_ID
    if [[ $core_ok == true ]]; then
      attach_default "$client" "$uuid" "$core_scope" "$core_scope_uuid"
    fi
  fi

  # 5. groups as full paths; a scope writing groups differently is detached from this client
  if [[ -n $uuid ]]; then
    while IFS= read -r line; do
      [[ -n $line ]] || continue
      name=${line##*,}
      rest=$(mapper_rest "$line")
      if [[ $name == "$GROUPS_MAPPER" && ${rest%%,*} == oidc-group-membership-mapper ]]; then
        own_groups_line=$line
        continue
      fi
      case $(groups_kind "$rest") in
        good) good+=("client mapper $name") ;;
        bad) bad_client+=("client mapper $name") ;;
      esac
    done < <(csv "clients/$uuid/protocol-mappers/models" "$MAPPER_FIELDS")
  fi
  for kind in default optional; do
    while IFS= read -r scope_name; do
      [[ -n $scope_name ]] || continue
      if [[ $kind == default ]]; then scope_id=${default_scopes[$scope_name]}; else scope_id=${optional_scopes[$scope_name]}; fi
      local scope_good=false scope_bad=false
      while IFS= read -r line; do
        [[ -n $line ]] || continue
        case $(groups_kind "$(mapper_rest "$line")") in
          good) scope_good=true ;;
          bad) scope_bad=true ;;
        esac
      done < <(csv "client-scopes/$scope_id/protocol-mappers/models" "$MAPPER_FIELDS")
      if [[ $scope_bad == true ]]; then
        change "detach the $kind scope $scope_name from $client (it writes the claim $GROUPS_CLAIM differently from what inscribed reads; the realm scope and other clients keep it)"
        if [[ $MODE == apply && -n $uuid ]]; then
          kcadm_write delete "clients/$uuid/$kind-client-scopes/$scope_id" -r "$TARGET_REALM"
        fi
      elif [[ $scope_good == true && $kind == default ]]; then
        good+=("default scope $scope_name")
      fi
    done < <(if [[ $kind == default ]]; then printf '%s\n' "${!default_scopes[@]}"; else printf '%s\n' "${!optional_scopes[@]}"; fi | sort)
  done
  if [[ ${#bad_client[@]} -gt 0 ]]; then
    problem "$client: the claim $GROUPS_CLAIM reaches the access token differently from what inscribed reads (${bad_client[*]}); not changed. Fix it by hand"
  fi
  if [[ -n $own_groups_line ]]; then
    if own_groups_ok "$(mapper_rest "$own_groups_line")"; then
      log "$client: mapper $GROUPS_MAPPER unchanged ($GROUPS_CLAIM, full path)"
    else
      change "repair mapper $GROUPS_MAPPER on $client ($(mapper_rest "$own_groups_line") -> Group Membership, claim $GROUPS_CLAIM, full path, access token and introspection)"
      if [[ $MODE == apply ]]; then
        kcadm_write update "clients/$uuid/protocol-mappers/models/${own_groups_line%%,*}" -r "$TARGET_REALM" \
          -b "$(groups_mapper_body "${own_groups_line%%,*}")"
      fi
    fi
  elif [[ ${#good[@]} -gt 0 ]]; then
    log "$client: $GROUPS_CLAIM (full path) comes from ${good[*]}"
  elif [[ ${#bad_client[@]} -eq 0 ]]; then
    local groups_scope_uuid
    groups_scope_uuid=$(realm_groups_scope)
    if [[ -n $groups_scope_uuid ]]; then
      attach_default "$client" "$uuid" "$GROUPS_SCOPE" "$groups_scope_uuid"
    else
      change "add mapper $GROUPS_MAPPER to $client (Group Membership: claim $GROUPS_CLAIM, full path, access token and introspection)"
      if [[ $MODE == apply ]]; then
        kcadm_write create "clients/$uuid/protocol-mappers/models" -r "$TARGET_REALM" -b "$(groups_mapper_body)"
      fi
    fi
  fi

  # 6. what comes next
  if [[ -n $uuid ]]; then
    sa_name=$(csv "clients/$uuid/service-account-user" username 2>/dev/null || true)
    [[ -z $sa_name ]] || log "$client: service account $sa_name (its CMS roles: inscribed-cms-roles.sh)"
  fi
  log "next: KEYCLOAK_REALM=$TARGET_REALM inscribed-cms-roles.sh --client $client --apply, then site-editor-grants.sh --site $site"
}

for site in "${SITES[@]}"; do
  ensure_site "$site"
done

# --- the hand-made clients: read-only report -------------------------------------------------------
for client in "${HAND_MADE_CLIENTS[@]}"; do
  uuid=$(uuid_by "$client")
  if [[ -z $uuid ]]; then
    log "NOTE: $client does not exist in realm $TARGET_REALM (not made here)"
    continue
  fi
  IFS=, read -r full_scope service_accounts direct_grants < <(csv "clients/$uuid" fullScopeAllowed,serviceAccountsEnabled,directAccessGrantsEnabled)
  redirects=$(csv "clients/$uuid" redirectUris | tr ',' ' ')
  skycms_from=''
  while IFS= read -r line; do
    [[ -n $line ]] || continue
    if is_audience_to "$(mapper_rest "$line")" "$RESOURCE_CLIENT"; then skycms_from+="${skycms_from:+, }client mapper ${line##*,}"; fi
  done < <(csv "clients/$uuid/protocol-mappers/models" "$MAPPER_FIELDS")
  while IFS=, read -r scope_id scope_name; do
    [[ -n $scope_id ]] || continue
    while IFS= read -r line; do
      [[ -n $line ]] || continue
      if is_audience_to "$(mapper_rest "$line")" "$RESOURCE_CLIENT"; then skycms_from+="${skycms_from:+, }default scope $scope_name"; fi
    done < <(csv "client-scopes/$scope_id/protocol-mappers/models" "$MAPPER_FIELDS")
  done < <(csv "clients/$uuid/default-client-scopes" id,name)
  log "hand-made $client (report only, never written here): fullScopeAllowed=$full_scope serviceAccountsEnabled=$service_accounts directAccessGrantsEnabled=$direct_grants; redirect URIs: ${redirects:-none}; aud $RESOURCE_CLIENT from: ${skycms_from:-nothing}"
done

